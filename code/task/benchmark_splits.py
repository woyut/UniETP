def benchmark_split(source_split: str, template_name: str) -> str:
    if source_split == "ins":
        return "linguistic"
    if source_split == "ref":
        return "instance_grounding"
    if source_split != "ori":
        raise ValueError(f"Unknown source split: {source_split!r}")
    try:
        return ORI_TEMPLATE_TO_SPLIT[template_name]
    except KeyError as exc:
        raise ValueError(
            f"Unclassified ori template_name: {template_name!r}"
        ) from exc
